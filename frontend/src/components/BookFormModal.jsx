import { useEffect, useState } from 'react';
import { X } from 'lucide-react';
import { BOOK_CATEGORIES, ISBN_REGEX } from '../utils/formatters';

export default function BookFormModal({
  isOpen,
  book,
  onClose,
  onSubmit,
  submitting,
  serverError,
}) {
  const isEditMode = Boolean(book);
  const issuedCopies = isEditMode ? book.totalCopies - book.availableCopies : 0;

  const [formData, setFormData] = useState({
    title: '',
    author: '',
    isbn: '',
    category: BOOK_CATEGORIES[0],
    totalCopies: '1',
  });
  const [errors, setErrors] = useState({});

  useEffect(() => {
    if (!isOpen) return;
    if (book) {
      setFormData({
        title: book.title || '',
        author: book.author || '',
        isbn: book.isbn || '',
        category: book.category || BOOK_CATEGORIES[0],
        totalCopies: String(book.totalCopies ?? 1),
      });
    } else {
      setFormData({
        title: '',
        author: '',
        isbn: '',
        category: BOOK_CATEGORIES[0],
        totalCopies: '1',
      });
    }
    setErrors({});
  }, [isOpen, book]);

  if (!isOpen) return null;

  const validate = () => {
    const nextErrors = {};
    const trimmedTitle = formData.title.trim();
    const trimmedAuthor = formData.author.trim();
    const trimmedIsbn = formData.isbn.trim();
    const copies = Number(formData.totalCopies);

    if (!trimmedTitle) {
      nextErrors.title = 'Title is required.';
    }
    if (!trimmedAuthor) {
      nextErrors.author = 'Author is required.';
    }
    if (!isEditMode) {
      if (!ISBN_REGEX.test(trimmedIsbn)) {
        nextErrors.isbn = 'ISBN must contain exactly 10 or 13 digits.';
      }
      if (!BOOK_CATEGORIES.includes(formData.category)) {
        nextErrors.category = 'Please select a valid category.';
      }
    }
    if (
      formData.totalCopies === '' ||
      !Number.isInteger(copies) ||
      copies < 1 ||
      copies > 20
    ) {
      nextErrors.totalCopies = 'Total Copies must be a whole number between 1 and 20.';
    } else if (isEditMode && copies < issuedCopies) {
      nextErrors.totalCopies = `Total Copies cannot be less than currently issued copies (${issuedCopies}).`;
    }

    setErrors(nextErrors);
    return Object.keys(nextErrors).length === 0;
  };

  const handleChange = (field, value) => {
    setFormData((prev) => ({ ...prev, [field]: value }));
    if (errors[field]) {
      setErrors((prev) => ({ ...prev, [field]: undefined }));
    }
  };

  const handleSubmit = (e) => {
    e.preventDefault();
    if (!validate()) return;

    if (isEditMode) {
      onSubmit({
        title: formData.title.trim(),
        author: formData.author.trim(),
        totalCopies: Number(formData.totalCopies),
      });
    } else {
      onSubmit({
        title: formData.title.trim(),
        author: formData.author.trim(),
        isbn: formData.isbn.trim(),
        category: formData.category,
        totalCopies: Number(formData.totalCopies),
      });
    }
  };

  return (
    <div className="modal-backdrop" role="dialog" aria-modal="true" aria-labelledby="book-modal-title">
      <div className="modal-card">
        <div className="modal-header">
          <div>
            <h2 id="book-modal-title">{isEditMode ? 'Edit Book Details' : 'Add New Book'}</h2>
            <p className="modal-subtitle">
              {isEditMode
                ? 'Book Code, ISBN, and Category are locked after creation.'
                : 'Book Code (LB-CAT-###) is auto-generated by the server.'}
            </p>
          </div>
          <button type="button" className="icon-btn" onClick={onClose} aria-label="Close modal">
            <X size={18} />
          </button>
        </div>

        <form onSubmit={handleSubmit} noValidate>
          <div className="modal-body">
            {serverError && (
              <div className="alert alert-error" role="alert">
                {serverError}
              </div>
            )}

            {isEditMode && (
              <div className="readonly-banner">
                <div>
                  <span className="readonly-label">Book Code</span>
                  <strong className="mono">{book.bookCode}</strong>
                </div>
                <div>
                  <span className="readonly-label">ISBN</span>
                  <strong className="mono">{book.isbn}</strong>
                </div>
                <div>
                  <span className="readonly-label">Category</span>
                  <strong>{book.category}</strong>
                </div>
              </div>
            )}

            <div className="form-group">
              <label htmlFor="book-title">Title *</label>
              <input
                id="book-title"
                type="text"
                placeholder="e.g., Clean Code"
                value={formData.title}
                onChange={(e) => handleChange('title', e.target.value)}
                className={errors.title ? 'input-error' : ''}
              />
              {errors.title && <span className="field-error">{errors.title}</span>}
            </div>

            <div className="form-group">
              <label htmlFor="book-author">Author *</label>
              <input
                id="book-author"
                type="text"
                placeholder="e.g., Robert C. Martin"
                value={formData.author}
                onChange={(e) => handleChange('author', e.target.value)}
                className={errors.author ? 'input-error' : ''}
              />
              {errors.author && <span className="field-error">{errors.author}</span>}
            </div>

            {!isEditMode && (
              <div className="form-row">
                <div className="form-group">
                  <label htmlFor="book-isbn">ISBN (10 or 13 digits) *</label>
                  <input
                    id="book-isbn"
                    type="text"
                    inputMode="numeric"
                    placeholder="e.g., 9780132350884"
                    value={formData.isbn}
                    onChange={(e) => handleChange('isbn', e.target.value)}
                    className={errors.isbn ? 'input-error' : ''}
                  />
                  {errors.isbn && <span className="field-error">{errors.isbn}</span>}
                </div>

                <div className="form-group">
                  <label htmlFor="book-category">Category *</label>
                  <select
                    id="book-category"
                    value={formData.category}
                    onChange={(e) => handleChange('category', e.target.value)}
                    className={errors.category ? 'input-error' : ''}
                  >
                    {BOOK_CATEGORIES.map((cat) => (
                      <option key={cat} value={cat}>
                        {cat}
                      </option>
                    ))}
                  </select>
                  {errors.category && <span className="field-error">{errors.category}</span>}
                </div>
              </div>
            )}

            <div className="form-group">
              <label htmlFor="book-copies">
                Total Copies (1–20) *
                {isEditMode && issuedCopies > 0 && (
                  <span className="label-hint"> (Currently issued: {issuedCopies})</span>
                )}
              </label>
              <input
                id="book-copies"
                type="number"
                min={isEditMode ? Math.max(1, issuedCopies) : 1}
                max={20}
                step={1}
                value={formData.totalCopies}
                onChange={(e) => handleChange('totalCopies', e.target.value)}
                className={errors.totalCopies ? 'input-error' : ''}
              />
              {errors.totalCopies && <span className="field-error">{errors.totalCopies}</span>}
            </div>
          </div>

          <div className="modal-footer">
            <button type="button" className="btn btn-secondary" onClick={onClose} disabled={submitting}>
              Cancel
            </button>
            <button type="submit" className="btn btn-primary" disabled={submitting}>
              {submitting ? 'Saving...' : isEditMode ? 'Save Changes' : 'Add Book'}
            </button>
          </div>
        </form>
      </div>
    </div>
  );
}
